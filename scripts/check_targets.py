#!/usr/bin/env python3
"""Validate target metadata and regenerate TARGETS.md.

Usage: scripts/check_targets.py [--write]
Fails if a file lacks required metadata, uses an unknown status, or claims
`status: formalized` while still containing `sorry`.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REQUIRED = ["id", "area", "status", "source", "statement-review"]
STATUSES = {"open", "proved-on-paper", "formalized"}
REVIEWS = {"unreviewed", "reviewed"}

def parse(path):
    text = path.read_text()
    m = re.search(r"/-!\n# (.+?)\n(.*?)-/", text, re.S)
    if not m:
        return None, text
    meta = {"title": m.group(1).strip()}
    for line in m.group(2).splitlines():
        km = re.match(r"- ([a-z-]+): (.+)", line)
        if km:
            meta[km.group(1)] = km.group(2).strip()
    return meta, text

def main():
    errors, rows, ids = [], [], set()
    for path in sorted((ROOT / "Targets").rglob("*.lean")):
        rel = path.relative_to(ROOT)
        meta, text = parse(path)
        if meta is None:
            errors.append(f"{rel}: missing `/-! # Title ... -/` header")
            continue
        for key in REQUIRED:
            if key not in meta:
                errors.append(f"{rel}: missing `{key}`")
        if meta.get("status") not in STATUSES:
            errors.append(f"{rel}: status must be one of {sorted(STATUSES)}")
        if meta.get("statement-review") not in REVIEWS:
            errors.append(f"{rel}: statement-review must be one of {sorted(REVIEWS)}")
        if meta.get("id") in ids:
            errors.append(f"{rel}: duplicate id {meta.get('id')}")
        ids.add(meta.get("id"))
        has_sorry = re.search(r"\bsorry\b", re.sub(r"/-.*?-/", "", text, flags=re.S)) is not None
        if meta.get("status") == "formalized" and has_sorry:
            errors.append(f"{rel}: status is `formalized` but the file contains `sorry`")
        rows.append((meta.get("area", ""), meta["title"], meta.get("status", ""),
                     meta.get("statement-review", ""), str(rel)))
    table = ["# Targets", "", "Generated by `scripts/check_targets.py --write`. Do not edit by hand.", "",
             "| Area | Target | Status | Statement review | File |", "|---|---|---|---|---|"]
    for area, title, status, review, rel in sorted(rows):
        table.append(f"| {area} | {title} | {status} | {review} | [{rel}]({rel}) |")
    out = "\n".join(table) + "\n"
    target = ROOT / "TARGETS.md"
    if "--write" in sys.argv:
        target.write_text(out)
    elif not target.exists() or target.read_text() != out:
        errors.append("TARGETS.md is stale; run scripts/check_targets.py --write")
    for e in errors:
        print("error:", e)
    print(f"{len(rows)} targets, {len(errors)} errors")
    sys.exit(1 if errors else 0)

if __name__ == "__main__":
    main()
